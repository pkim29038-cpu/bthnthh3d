const nobleSymbols=Object.freeze({He:2,Ne:10,Ar:18,Kr:36,Xe:54,Rn:86,Og:118});
const sups={'0':'⁰','1':'¹','2':'²','3':'³','4':'⁴','5':'⁵','6':'⁶','7':'⁷','8':'⁸','9':'⁹'};
const parseConfigText=raw=>raw?
  raw.replace(/\s*\(predicted\)\s*/gi,'').trim()
    .replace(/([spdf])(\d{1,2})\b/g,(_,orb,n)=>orb+[...n].map(d=>sups[d]).join(''))
  :null;

export function propertyFor(element){
  const record=periodicProperties[element.symbol];
  if(!record||record.z!==element.number)throw new Error('Missing atomic-property record '+element.symbol);
  return record;
}
export const formatElectronConfiguration=parseConfigText;
export function fullElectronConfiguration(element){
  const record=propertyFor(element);
  let expanded=record.config||'';
  let guard=0;
  while(/\[(He|Ne|Ar|Kr|Xe|Rn)\]/.test(expanded)&&guard++<7){
    const m=expanded.match(/\[(He|Ne|Ar|Kr|Xe|Rn)\]/);
    if(!m)break;
    const core=Object.entries(periodicProperties).find(([sym])=>sym===m[1]);
    if(!core?.[1]?.config)break;
    expanded=expanded.replace(m[0],core[1].config);
  }
  return parseConfigText(expanded);
}
export function compactElectronConfiguration(element){return parseConfigText(propertyFor(element).config);}
export function standardStateName(element){
  const s=propertyFor(element).state;
  return s==='Solid'?'Rắn':s==='Liquid'?'Lỏng':s==='Gas'?'Khí':null;
}
export function kelvinToCelsius(value){
  if(value==null||value==='')return null;
  const kelvin=Number(value);return Number.isFinite(kelvin)?kelvin-273.15:null;
}
